function AccordionItem({ section }: { section: DocSection }) {
  const [open, setOpen] = useState(false);
  const Icon = section.icon;
  return (
    <div className="rounded-xl border border-[var(--border)] bg-[var(--card)] overflow-hidden">
      <button
        className="flex w-full items-center gap-3 px-5 py-4 text-left hover:bg-black/5 dark:hover:bg-white/5 transition-colors"
        onClick={() => setOpen((o) => !o)}
      >
        <span className="flex h-8 w-8 shrink-0 items-center justify-center rounded-lg bg-brand-100 text-brand-600 dark:bg-brand-900/50">
          <Icon className="h-4 w-4" />
        </span>
        <span className="flex-1 font-semibold">{section.title}</span>
        <span className="text-[var(--muted)]">
          {open ? <ChevronDown className="h-4 w-4" /> : <ChevronRight className="h-4 w-4" />}
        </span>
      </button>
      {open && (
        <div className="border-t border-[var(--border)] divide-y divide-[var(--border)]">
          {section.items.map((item) => {
            const ItemIcon = item.icon;
            return (
              <div key={item.name} className="px-5 py-4">
                <div className="flex items-center gap-2 mb-1">
                  {ItemIcon && <ItemIcon className="h-3.5 w-3.5 text-brand-500 shrink-0" />}
                  <p className="font-medium text-sm">{item.name}</p>
                  {item.shortcut && (
                    <kbd className="ml-auto shrink-0 rounded bg-black/10 px-2 py-0.5 font-mono text-[10px] dark:bg-white/10">
                      {item.shortcut}
                    </kbd>
                  )}
                </div>
                <p className="text-sm text-[var(--muted)] leading-relaxed pl-5 sm:pl-6">
                  {item.desc}
                </p>
              </div>
            );
          })}
        </div>
      )}
    </div>
  );
}

